def _actions_for(
    *,
    source: DiscussionSource,
    author_id: uuid.UUID,
    user: User,
    project_role: str | None = None,
    is_manager: bool = False,
):
    """Comment actions derived from the *resolved project access*.

    A global platform ``reviewer`` is not a moderator; the current reviewer
    membership is, and management is owner/super-admin.
    """
    return discussion_actions(
        source,
        "comment",
        is_author=author_id == user.id,
        is_admin=is_manager,
        is_reviewer=project_role == ProjectRole.REVIEWER.value,
        is_accessible=True,
        # Native task comments and legacy annotation comments have no Issue thread
        # affordance in this product scope.
        can_reply=False,
    )


def _identifier_selects(
    *,
    task_id: uuid.UUID | ColumnElement[Any],
    scope: DiscussionScope,
    annotation_id: uuid.UUID | ColumnElement[Any] | None,
    project_id: uuid.UUID | ColumnElement[Any],
):
    """Return the source identifier SELECTs used by the single read model query."""

    selects = []
    if scope in {"all", "annotation"}:
        annotation_query = (
            select(
                AnnotationComment.id.label("item_id"),
                AnnotationComment.created_at.label("created_at"),
                literal("annotation_comment").label("source"),
            )
            .join(Annotation, Annotation.id == AnnotationComment.annotation_id)
            .where(
                Annotation.task_id == task_id,
                AnnotationComment.is_active.is_(True),
            )
        )
        if annotation_id is not None:
            annotation_query = annotation_query.where(Annotation.id == annotation_id)
        selects.append(annotation_query)

    if scope in {"all", "task"}:
        # ``anchor_type=task`` and a NULL parent identify native task-comment roots.
        # Joining the task project in the predicate guards malformed legacy rows whose
        # denormalized project_id no longer agrees with the actual task.
        selects.append(
            select(
                AnnotationFeedback.id.label("item_id"),
                AnnotationFeedback.created_at.label("created_at"),
                literal("feedback").label("source"),
            ).where(
                AnnotationFeedback.project_id == project_id,
                AnnotationFeedback.task_id == task_id,
                AnnotationFeedback.kind == "comment",
                AnnotationFeedback.anchor_type == "task",
                AnnotationFeedback.thread_parent_id.is_(None),
                AnnotationFeedback.is_active.is_(True),
            )
        )
    return selects


def task_comment_count_sq() -> ColumnElement[int]:
    """Correlated count of the complete Workbench comment feed per ``Task`` row.

    Reuses ``_identifier_selects`` so Data Manager task counts always agree with
    the discussion panel total: active annotation comments (including comments
    on soft-deleted annotations) plus active native task comments. Issue posts,
    issue replies and mirrored annotation comments never count.
    """

    # The union hides the Task references from auto-correlation, so correlate
    # each source select explicitly to keep the count attached to the outer
    # task row instead of counting the whole table.
    source_selects = _identifier_selects(
        task_id=Task.id,
        scope="all",
        annotation_id=None,
        project_id=Task.project_id,
    )
    identifiers = union_all(
        *(item.correlate(Task) for item in source_selects)
    ).subquery()
    return select(func.count()).select_from(identifiers).scalar_subquery()


async def list_task_discussion(
    db: AsyncSession,
    *,
    task: Task,
    user: User,
    scope: DiscussionScope,
    annotation_id: uuid.UUID | None,
    limit: int,
    cursor: str | None = None,
) -> TaskDiscussionPage:
    """Read one correctly ordered page from both authoritative comment sources."""

    source_selects = _identifier_selects(
        task_id=task.id,
        scope=scope,
        annotation_id=annotation_id,
        project_id=task.project_id,
    )
    identifiers = union_all(*source_selects).subquery("discussion_identifiers")

    total = int(await db.scalar(select(func.count()).select_from(identifiers)) or 0)

    position: DiscussionCursor | None = None
    if cursor is not None:
        position = decode_discussion_cursor(
            cursor,
            task_id=task.id,
            scope=scope,
            annotation_id=annotation_id,
        )

    page_query = select(
        identifiers.c.item_id,
        identifiers.c.created_at,
        identifiers.c.source,
    )
    if position is not None:
        page_query = page_query.where(
            or_(
                identifiers.c.created_at < position.created_at,
                and_(
                    identifiers.c.created_at == position.created_at,
                    identifiers.c.source < position.source,
                ),
                and_(
                    identifiers.c.created_at == position.created_at,
                    identifiers.c.source == position.source,
                    identifiers.c.item_id < position.item_id,
                ),
            )
        )
    page_query = page_query.order_by(
        identifiers.c.created_at.desc(),
        identifiers.c.source.desc(),
        identifiers.c.item_id.desc(),
    ).limit(limit + 1)
    identifier_rows = list((await db.execute(page_query)).all())
    has_next = len(identifier_rows) > limit
    page_identifiers = identifier_rows[:limit]

    next_cursor: str | None = None
    if has_next and page_identifiers:
        last = page_identifiers[-1]
        next_cursor = encode_discussion_cursor(
            task_id=task.id,
            scope=scope,
            annotation_id=annotation_id,
            created_at=last.created_at,
            source=last.source,
            item_id=last.item_id,
        )

    # Hydrate each source once for the page.  In particular, maps are keyed by
    # (source, id), never by id alone, because PostgreSQL UUIDs may coincide across
    # the two source tables.
    annotation_ids = [
        row.item_id for row in page_identifiers if row.source == "annotation_comment"
    ]
    feedback_ids = [row.item_id for row in page_identifiers if row.source == "feedback"]

    annotation_by_id: dict[uuid.UUID, tuple[AnnotationComment, str | None]] = {}
    if annotation_ids:
        annotation_rows = (
            await db.execute(
                select(AnnotationComment, User.name)
                .join(User, User.id == AnnotationComment.author_id)
                .where(AnnotationComment.id.in_(annotation_ids))
            )
        ).all()
        annotation_by_id = {
            comment.id: (comment, name) for comment, name in annotation_rows
        }

    feedback_by_id: dict[uuid.UUID, AnnotationFeedback] = {}
    if feedback_ids:
        feedback_rows = (
            (
                await db.execute(
                    select(AnnotationFeedback).where(
                        AnnotationFeedback.id.in_(feedback_ids)
                    )
                )
            )
            .scalars()
            .all()
        )
        feedback_by_id = {feedback.id: feedback for feedback in feedback_rows}

    feedback_briefs = await resolve_briefs(
        db,
        [feedback.author_id for feedback in feedback_by_id.values()],
    )

    # Resolve the current project access once so comment actions use the
    # project role rather than the account's legacy global role.
    from app.db.models.project import Project
    from app.services.project_access import resolve_project_access

    project = await db.get(Project, task.project_id)
    access = await resolve_project_access(db, user=user, project=project)

    items: list[TaskDiscussionItem] = []
    for row in page_identifiers:
        if row.source == "annotation_comment":
            hydrated = annotation_by_id.get(row.item_id)
            if hydrated is None:  # pragma: no cover - same snapshot guarantees this
                continue
            comment, author_name = hydrated
            data: AnnotationCommentOut | AnnotationFeedbackOut = (
                _annotation_comment_out(comment, author_name)
            )
            actions = _actions_for(
                source="annotation_comment",
                author_id=comment.author_id,
                user=user,
                project_role=access.project_role,
                is_manager=access.is_manager,
            )
            source: DiscussionSource = "annotation_comment"
        else:
            feedback = feedback_by_id.get(row.item_id)
            if feedback is None:  # pragma: no cover - same snapshot guarantees this
                continue
            brief = feedback_briefs.get(str(feedback.author_id))
            data = _feedback_out(feedback, brief.name if brief is not None else None)
            actions = _actions_for(
                source="feedback",
                author_id=feedback.author_id,
                user=user,
                project_role=access.project_role,
                is_manager=access.is_manager,
            )
            source = "feedback"
        items.append(TaskDiscussionItem(source=source, data=data, actions=actions))

    return TaskDiscussionPage(
        items=items,
        next_cursor=next_cursor,
        total=total,
    )
