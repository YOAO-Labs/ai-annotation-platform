"""Authoritative task discussion read model.

The legacy ``annotation_comments`` table and the native task-comment rows in
``annotation_feedbacks`` are both still write-owned by their existing APIs.  This
module only composes their identifiers for one keyset-ordered read, then hydrates
each source in batches.  Annotation feedback mirrors, Issue threads, BUGs and task
rejection mirrors are intentionally not part of this read model.
"""

